import React, { useState, useMemo } from 'react';
import {
  Calendar,
  Clock,
  Users,
  CheckCircle2,
  X,
  AlertTriangle,
  UserCheck,
  Building,
  Sparkles,
  AlertCircle,
  HelpCircle,
} from 'lucide-react';
import type { DayOfWeek } from '@/core/staff/workWindow';
import { rosterStorage } from '@/capabilities/roster/infrastructure/rosterStorage';
import { showToast } from '@/shared/feedback/uiFeedback';

export interface AssignableStudent {
  id: string;
  name: string;
  classIds?: string[];
  status?: string;
  grade?: string;
}

interface BulkScheduleAssignModalProps {
  isOpen: boolean;
  onClose: () => void;
  selectedStudents: AssignableStudent[];
  onAssigned: (message: string) => void;
  onNavigateToTimetable?: () => void;
}

const ALL_DAYS: { key: DayOfWeek; label: string }[] = [
  { key: '월', label: '월' },
  { key: '화', label: '화' },
  { key: '수', label: '수' },
  { key: '목', label: '목' },
  { key: '금', label: '금' },
  { key: '토', label: '토' },
  { key: '일', label: '일' },
];

const QUICK_TIME_SLOTS = [
  '13:00',
  '13:30',
  '14:00',
  '14:30',
  '15:00',
  '15:30',
  '16:00',
  '16:30',
  '17:00',
  '17:30',
  '18:00',
  '18:30',
  '19:00',
];

const DURATION_OPTIONS = [
  { minutes: 30, label: '30분 수업' },
  { minutes: 40, label: '40분 수업' },
  { minutes: 50, label: '50분 수업' },
  { minutes: 60, label: '60분 수업' },
];

// 엣지 8번: 원내 브레이크 타임 슬롯
const BREAK_TIME_SLOTS = ['12:00', '12:30', '17:30'];

function calculateEndTime(startTime: string, durationMinutes: number): string {
  const [hStr, mStr] = startTime.split(':');
  const h = parseInt(hStr, 10) || 15;
  const m = parseInt(mStr, 10) || 0;
  const totalMinutes = h * 60 + m + durationMinutes;
  const endH = Math.floor(totalMinutes / 60);
  const endM = totalMinutes % 60;
  return `${String(endH).padStart(2, '0')}:${String(endM).padStart(2, '0')}`;
}

export const BulkScheduleAssignModal: React.FC<BulkScheduleAssignModalProps> = ({
  isOpen,
  onClose,
  selectedStudents,
  onAssigned,
  onNavigateToTimetable,
}) => {
  const [assignMode, setAssignMode] = useState<'create_new' | 'join_existing'>('create_new');

  // 신규 반 생성 폼 상태
  const [selectedDays, setSelectedDays] = useState<DayOfWeek[]>(['월', '수', '금']);
  const [startTime, setStartTime] = useState<string>('15:00');
  const [durationMinutes, setDurationMinutes] = useState<number>(50);
  const [customClassName, setCustomClassName] = useState<string>('');
  const [selectedTeacherId, setSelectedTeacherId] = useState<string>('');
  const [selectedRoom, setSelectedRoom] = useState<string>('1번 연습실');
  const [capacity, setCapacity] = useState<number>(5);
  // 7번: 요일별 개별 시간 지정 상태
  const [customTimePerDay, setCustomTimePerDay] = useState<boolean>(false);
  const [dayTimes, setDayTimes] = useState<Record<string, string>>({});

  // 기존 반 참여 폼 상태
  const [selectedExistingClassId, setSelectedExistingClassId] = useState<string>('');
  const [allowOverCapacity, setAllowOverCapacity] = useState<boolean>(false);

  // 엣지 1번: 시간표 중복 충돌 시 해결 옵션 ('keep_both' | 'replace_conflicting')
  const [conflictResolution, setConflictResolution] = useState<'keep_both' | 'replace_conflicting'>('replace_conflicting');
  const [assignedResult, setAssignedResult] = useState<{ count: number; className: string } | null>(null);

  // Storage 데이터 조회
  const teachers = useMemo(() => {
    if (typeof window === 'undefined') return [];
    try {
      return rosterStorage.getTeachers?.() || [];
    } catch {
      return [];
    }
  }, []);

  const existingClasses = useMemo(() => {
    if (typeof window === 'undefined') return [];
    try {
      return rosterStorage.getClasses?.() || [];
    } catch {
      return [];
    }
  }, []);

  const allStudents = useMemo(() => {
    if (typeof window === 'undefined') return [];
    try {
      return rosterStorage.getStudents?.() || [];
    } catch {
      return [];
    }
  }, []);

  const endTime = useMemo(() => {
    return calculateEndTime(startTime, durationMinutes);
  }, [startTime, durationMinutes]);

  const autoGeneratedName = useMemo(() => {
    const dayStr = selectedDays.join('');
    return `${dayStr} ${startTime} 정규반`;
  }, [selectedDays, startTime]);

  const targetClassName = customClassName.trim() || autoGeneratedName;

  // 요일 토글
  const toggleDay = (day: DayOfWeek) => {
    setSelectedDays((prev) =>
      prev.includes(day) ? prev.filter((d) => d !== day) : [...prev, day]
    );
  };

  // 프리셋 요일 설정
  const applyPresetDays = (days: DayOfWeek[]) => {
    setSelectedDays(days);
  };

  // =========================================================================
  // 엣지 1번: 시간표 중복 충돌 계산 (Schedule Conflict)
  // =========================================================================
  const conflictStudents = useMemo(() => {
    if (assignMode !== 'create_new' || selectedDays.length === 0) return [];

    // 배정하려는 시간대와 겹치는 기존 반 탐색
    const overlappingClasses = existingClasses.filter((c) => {
      const hasSameDay = c.daysOfWeek?.some((d) => selectedDays.includes(d as DayOfWeek));
      if (!hasSameDay) return false;
      return startTime < c.endTime && endTime > c.startTime;
    });

    const conflicts: { student: AssignableStudent; conflictingClass: typeof overlappingClasses[0] }[] = [];
    for (const st of selectedStudents) {
      for (const cls of overlappingClasses) {
        if (st.classIds?.includes(cls.id)) {
          conflicts.push({ student: st, conflictingClass: cls });
        }
      }
    }
    return conflicts;
  }, [assignMode, selectedDays, startTime, endTime, existingClasses, selectedStudents]);

  // =========================================================================
  // 엣지 2번: 정원 초과 계산 (Capacity Overflow)
  // =========================================================================
  const selectedExistingClass = useMemo(() => {
    return existingClasses.find((c) => c.id === selectedExistingClassId);
  }, [existingClasses, selectedExistingClassId]);

  const existingEnrolledCount = useMemo(() => {
    if (!selectedExistingClass) return 0;
    return allStudents.filter((s) => s.classIds?.includes(selectedExistingClass.id)).length;
  }, [allStudents, selectedExistingClass]);

  const alreadyAssignedStudents = useMemo(() => {
    if (!selectedExistingClass) return [];
    return selectedStudents.filter((s) => s.classIds?.includes(selectedExistingClass.id));
  }, [selectedExistingClass, selectedStudents]);

  const newlyAddingCount = selectedStudents.length - alreadyAssignedStudents.length;
  const expectedTotalCount = existingEnrolledCount + newlyAddingCount;
  const maxCapacity = selectedExistingClass
    ? selectedExistingClass.capacity || 5
    : capacity;
  const isOverCapacity = assignMode === 'join_existing' && expectedTotalCount > maxCapacity;

  if (!isOpen) return null;

  const handleConfirmAssign = () => {
    if (selectedStudents.length === 0) return;

    if (isOverCapacity && !allowOverCapacity) {
      showToast(`정원(${maxCapacity}명)을 초과합니다. 초과 배정을 원하시면 '정원 초과 허용'을 체크해주세요.`, 'warning');
      return;
    }

    try {
      let targetClassIds: string[] = [];
      let finalClassName = '';
      const removedConflictsMap: Record<string, string[]> = {};

      if (assignMode === 'create_new') {
        if (selectedDays.length === 0) {
          showToast('수업 요일을 최소 1개 이상 선택해주세요.', 'warning');
          return;
        }

        const teacher = teachers.find((t) => t.id === selectedTeacherId);
        const teacherName = teacher?.name || '담당 강사';

        if (customTimePerDay && selectedDays.length > 1) {
          // 7번: 요일마다 다른 시작 시간 지정 시 요일별 개별 반 생성
          for (const d of selectedDays) {
            const dayStart = dayTimes[d] || startTime;
            const dayEnd = calculateEndTime(dayStart, durationMinutes);
            const dayName = customClassName.trim()
              ? `${customClassName.trim()} (${d} ${dayStart})`
              : `${d} ${dayStart} 피아노`;

            const newClass = rosterStorage.saveClass({
              name: dayName,
              teacherId: selectedTeacherId || 'teacher_default',
              teacherName,
              daysOfWeek: [d],
              startTime: dayStart,
              endTime: dayEnd,
              capacity: Math.max(capacity, selectedStudents.length),
              room: selectedRoom,
              memo: `[일괄 배정-요일별] ${new Date().toLocaleDateString('ko-KR')} 생성됨`,
            });
            targetClassIds.push(newClass.id);
          }
          finalClassName = `${selectedDays.join('/')} 요일별 맞춤 (${targetClassIds.length}개 슬롯)`;
        } else {
          // 1. 단일 시간대 새 ClassItem 생성 및 저장 (정원은 선택 학생 수 이상으로 자동 보정)
          const newClass = rosterStorage.saveClass({
            name: targetClassName,
            teacherId: selectedTeacherId || 'teacher_default',
            teacherName,
            daysOfWeek: selectedDays,
            startTime,
            endTime,
            capacity: Math.max(capacity, selectedStudents.length),
            room: selectedRoom,
            memo: `[일괄 배정] ${new Date().toLocaleDateString('ko-KR')} 생성됨`,
          });

          targetClassIds.push(newClass.id);
          finalClassName = newClass.name;
        }

        // 엣지 1번: 충돌 반 교체 처리 시 제거할 classId 매핑
        if (conflictResolution === 'replace_conflicting') {
          for (const conf of conflictStudents) {
            if (!removedConflictsMap[conf.student.id]) {
              removedConflictsMap[conf.student.id] = [];
            }
            removedConflictsMap[conf.student.id].push(conf.conflictingClass.id);
          }
        }
      } else {
        const found = selectedExistingClass;
        if (!found) {
          showToast('배정할 기존 반을 선택해주세요.', 'warning');
          return;
        }
        targetClassIds.push(found.id);
        finalClassName = found.name;
      }

      // 2. 선택된 모든 학생의 classIds 갱신 (엣지 3번: 중복 방지 new Set)
      let updatedCount = 0;
      for (const st of selectedStudents) {
        const currentClassIds = Array.isArray(st.classIds) ? st.classIds : [];
        const toRemove = removedConflictsMap[st.id] || [];
        const filteredIds = currentClassIds.filter((cid) => !toRemove.includes(cid));

        const toAdd = targetClassIds.filter((cid) => !filteredIds.includes(cid));
        if (toAdd.length > 0) {
          const nextClassIds = Array.from(new Set([...filteredIds, ...targetClassIds]));
          rosterStorage.saveStudent({
            ...st,
            classIds: nextClassIds,
          } as any);
          updatedCount++;
        }
      }

      const msg = `${selectedStudents.length}명이 [${finalClassName}] 시간표에 성공적으로 배정되었습니다! (신규 등록: ${updatedCount}명)`;
      onAssigned(msg);
      if (onNavigateToTimetable) {
        setAssignedResult({ count: selectedStudents.length, className: finalClassName });
      } else {
        onClose();
      }
    } catch (err) {
      console.error('시간표 일괄 배정 중 오류 발생:', err);
      showToast('배정 중 오류가 발생했습니다. 다시 시도해주세요.', 'error');
    }
  };

  const handleClose = () => {
    setAssignedResult(null);
    onClose();
  };

  return (
    <div
      className="fixed inset-0 z-50 overflow-y-auto bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-4"
      role="dialog"
      aria-modal="true"
      aria-labelledby="bulk-assign-title"
    >
      <div className="bg-white rounded-3xl shadow-2xl max-w-lg w-full overflow-hidden border border-slate-200 animate-in fade-in zoom-in-95 duration-150">
        {assignedResult ? (
          /* 배정 완료 화면 (2번: 주간 시간표 즉시 연결 내비게이션) */
          <div className="p-6 sm:p-8 text-center space-y-5">
            <div className="w-16 h-16 rounded-3xl bg-emerald-100 text-emerald-600 flex items-center justify-center mx-auto shadow-inner">
              <CheckCircle2 className="w-9 h-9" />
            </div>
            <div>
              <h3 className="text-xl font-black text-slate-900 tracking-tight">시간표 배정 완료!</h3>
              <p className="text-xs sm:text-sm text-slate-600 mt-1.5 leading-relaxed">
                선택한 <strong className="text-indigo-600 font-bold">{assignedResult.count}명</strong>이{' '}
                <strong className="text-slate-900 font-bold">[{assignedResult.className}]</strong> 수업 시간표에 성공적으로 배정되었습니다.
              </p>
            </div>
            <div className="pt-2 flex flex-col sm:flex-row gap-2.5">
              <button
                type="button"
                onClick={() => {
                  handleClose();
                  onNavigateToTimetable?.();
                }}
                className="flex-1 min-h-[44px] px-5 py-3 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white font-black text-xs sm:text-sm shadow-md transition-all flex items-center justify-center gap-2 cursor-pointer"
              >
                <span>주간 시간표에서 바로 확인하기 →</span>
              </button>
              <button
                type="button"
                onClick={handleClose}
                className="min-h-[44px] px-4 py-3 rounded-xl border border-slate-200 text-slate-600 hover:bg-slate-100 font-bold text-xs sm:text-sm transition-colors cursor-pointer"
              >
                확인 (닫기)
              </button>
            </div>
          </div>
        ) : (
          <>
            {/* 모달 헤더 */}
            <div className="p-5 sm:p-6 border-b border-slate-100 flex items-center justify-between bg-slate-50/70">
              <div className="flex items-center gap-3">
                <div className="w-10 h-10 rounded-2xl bg-indigo-600 flex items-center justify-center text-white shadow-md shadow-indigo-600/20">
                  <Calendar className="w-5 h-5" />
                </div>
                <div>
                  <h2 id="bulk-assign-title" className="text-lg font-black text-slate-900 tracking-tight">
                    시간표 일괄 배정
                  </h2>
                  <p className="text-xs text-slate-500 mt-0.5">
                    선택된 <strong className="text-indigo-600 font-bold">{selectedStudents.length}명</strong>을 원하는 시간표 슬롯에 한 번에 배정합니다.
                  </p>
                </div>
              </div>
              <button
                type="button"
                onClick={handleClose}
            className="p-2 text-slate-400 hover:text-slate-600 hover:bg-slate-100 rounded-xl transition-colors cursor-pointer"
            aria-label="닫기"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* 선택된 명단 미리보기 배너 */}
        <div className="px-5 py-3 bg-indigo-50/50 border-b border-indigo-100/60 flex items-center gap-2 overflow-x-auto text-xs">
          <span className="font-bold text-indigo-950 shrink-0 flex items-center gap-1">
            <Users className="w-3.5 h-3.5 text-indigo-600" />
            배정 대상:
          </span>
          <div className="flex items-center gap-1.5 flex-wrap max-h-16 overflow-y-auto">
            {selectedStudents.slice(0, 8).map((st) => (
              <span
                key={st.id}
                className="px-2 py-0.5 bg-white border border-indigo-200 text-indigo-700 font-semibold rounded-lg shadow-2xs"
              >
                {st.name}
              </span>
            ))}
            {selectedStudents.length > 8 && (
              <span className="text-[11px] font-bold text-indigo-600">
                외 {selectedStudents.length - 8}명
              </span>
            )}
          </div>
        </div>

        {/* 엣지 4번: 주당 레슨 빈도 안내 칩 */}
        {selectedDays.length >= 3 && assignMode === 'create_new' && (
          <div className="mx-5 sm:mx-6 mt-4 p-2.5 rounded-xl bg-blue-50 border border-blue-200 text-blue-900 text-xs flex items-center gap-2">
            <AlertCircle className="w-4 h-4 text-blue-600 shrink-0" />
            <p>
              선택된 요일은 <strong>주 {selectedDays.length}회({selectedDays.join('')})</strong>입니다. 등록 수강권 잔여 횟수를 고려하여 배정하세요.
            </p>
          </div>
        )}

        {/* 엣지 8번: 브레이크 타임 슬롯 경고 배너 */}
        {BREAK_TIME_SLOTS.includes(startTime) && assignMode === 'create_new' && (
          <div className="mx-5 sm:mx-6 mt-3 p-2.5 rounded-xl bg-rose-50 border border-rose-200 text-rose-900 text-xs flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 text-rose-600 shrink-0" />
            <p>
              선택한 시작 시간(<strong>{startTime}</strong>)은 원내 브레이크(점심/소독 휴게) 시간입니다. 정규 수업 일정이 맞는지 확인하세요.
            </p>
          </div>
        )}

        {/* 엣지 1번: 시간표 중복 충돌 감지 배너 */}
        {conflictStudents.length > 0 && (
          <div className="mx-5 sm:mx-6 mt-3 p-3.5 rounded-2xl bg-amber-50 border border-amber-200 text-amber-900 text-xs space-y-2">
            <div className="flex items-start gap-2 font-bold text-amber-950">
              <AlertTriangle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
              <div>
                <p>동일 시간대에 이미 다른 수업이 있는 학생 {conflictStudents.length}명 발견</p>
                <p className="text-[11px] font-normal text-amber-800 mt-0.5">
                  {conflictStudents.map((c) => `${c.student.name}(${c.conflictingClass.name})`).join(', ')}
                </p>
              </div>
            </div>
            <div className="pt-1 flex items-center gap-4 text-xs font-semibold">
              <label className="inline-flex items-center gap-1.5 cursor-pointer">
                <input
                  type="radio"
                  name="conflictResolution"
                  value="replace_conflicting"
                  checked={conflictResolution === 'replace_conflicting'}
                  onChange={() => setConflictResolution('replace_conflicting')}
                  className="text-amber-600"
                />
                <span>기존 충돌 반에서 교체(권장)</span>
              </label>
              <label className="inline-flex items-center gap-1.5 cursor-pointer">
                <input
                  type="radio"
                  name="conflictResolution"
                  value="keep_both"
                  checked={conflictResolution === 'keep_both'}
                  onChange={() => setConflictResolution('keep_both')}
                  className="text-amber-600"
                />
                <span>기존 반 유지하고 추가</span>
              </label>
            </div>
          </div>
        )}

        {/* 배정 모드 탭 (신규 반 생성 vs 기존 반 연결) */}
        <div className="p-5 sm:p-6 space-y-5">
          <div className="grid grid-cols-2 gap-2 p-1 bg-slate-100 rounded-2xl">
            <button
              type="button"
              onClick={() => setAssignMode('create_new')}
              className={`py-2 px-3 text-xs font-black rounded-xl transition-all cursor-pointer ${
                assignMode === 'create_new'
                  ? 'bg-white text-indigo-700 shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              새 시간표 슬롯 생성
            </button>
            <button
              type="button"
              onClick={() => setAssignMode('join_existing')}
              className={`py-2 px-3 text-xs font-black rounded-xl transition-all cursor-pointer ${
                assignMode === 'join_existing'
                  ? 'bg-white text-indigo-700 shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              기존 반에 연결
            </button>
          </div>

          {/* MODE 1: 신규 반 생성 */}
          {assignMode === 'create_new' ? (
            <div className="space-y-4">
              {/* 요일 선택 */}
              <div>
                <div className="flex items-center justify-between mb-2">
                  <label className="text-xs font-black text-slate-700 flex items-center gap-1.5">
                    <Calendar className="w-3.5 h-3.5 text-indigo-600" />
                    수업 요일 선택
                  </label>
                  <div className="flex items-center gap-1">
                    <button
                      type="button"
                      onClick={() => applyPresetDays(['월', '수', '금'])}
                      className="text-[11px] font-bold px-2 py-0.5 rounded-lg bg-indigo-50 text-indigo-700 hover:bg-indigo-100 cursor-pointer"
                    >
                      월수금
                    </button>
                    <button
                      type="button"
                      onClick={() => applyPresetDays(['화', '목'])}
                      className="text-[11px] font-bold px-2 py-0.5 rounded-lg bg-indigo-50 text-indigo-700 hover:bg-indigo-100 cursor-pointer"
                    >
                      화목
                    </button>
                    <button
                      type="button"
                      onClick={() => applyPresetDays(['월', '화', '수', '목', '금'])}
                      className="text-[11px] font-bold px-2 py-0.5 rounded-lg bg-slate-100 text-slate-700 hover:bg-slate-200 cursor-pointer"
                    >
                      평일매일
                    </button>
                  </div>
                </div>
                <div className="grid grid-cols-7 gap-1.5">
                  {ALL_DAYS.map((d) => {
                    const isSelected = selectedDays.includes(d.key);
                    return (
                      <button
                        key={d.key}
                        type="button"
                        onClick={() => toggleDay(d.key)}
                        className={`min-h-[44px] flex items-center justify-center rounded-xl text-xs font-black transition-all cursor-pointer ${
                          isSelected
                            ? 'bg-indigo-600 text-white shadow-xs'
                            : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                        }`}
                      >
                        {d.label}
                      </button>
                    );
                  })}
                </div>
              </div>

              {/* 시간대 선택 */}
              <div>
                <label className="text-xs font-black text-slate-700 flex items-center gap-1.5 mb-2">
                  <Clock className="w-3.5 h-3.5 text-indigo-600" />
                  시작 시간
                </label>
                <div className="grid grid-cols-4 sm:grid-cols-5 gap-1.5 max-h-32 overflow-y-auto p-1 border border-slate-200 rounded-xl">
                  {QUICK_TIME_SLOTS.map((slot) => {
                    const isSelected = startTime === slot;
                    return (
                      <button
                        key={slot}
                        type="button"
                        onClick={() => setStartTime(slot)}
                        className={`py-1.5 text-xs font-mono font-bold rounded-lg transition-colors cursor-pointer ${
                          isSelected
                            ? 'bg-indigo-600 text-white shadow-xs'
                            : 'bg-slate-50 text-slate-700 hover:bg-indigo-50'
                        }`}
                      >
                        {slot}
                      </button>
                    );
                  })}
                </div>
              </div>

              {/* 7번: 요일마다 다른 시작 시간 지정 */}
              {selectedDays.length > 1 && (
                <div className="pt-1">
                  <label className="flex items-center gap-2 cursor-pointer text-xs font-bold text-slate-800">
                    <input
                      type="checkbox"
                      checked={customTimePerDay}
                      onChange={(e) => setCustomTimePerDay(e.target.checked)}
                      className="rounded text-indigo-600 focus:ring-indigo-500"
                    />
                    <span>요일마다 다른 시간에 시작하기 (요일별 개별 시간 지정)</span>
                  </label>
                  {customTimePerDay && (
                    <div className="mt-2.5 p-3 rounded-2xl bg-indigo-50/70 border border-indigo-100 space-y-2">
                      <p className="text-[11px] font-bold text-indigo-950">선택한 요일별 시작 시간</p>
                      <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
                        {selectedDays.map((d) => (
                          <div
                            key={d}
                            className="p-2 rounded-xl bg-white border border-indigo-200/80 flex items-center justify-between gap-1 shadow-2xs"
                          >
                            <span className="font-black text-xs text-indigo-950">{d}요일</span>
                            <select
                              value={dayTimes[d] || startTime}
                              onChange={(e) =>
                                setDayTimes((prev) => ({ ...prev, [d]: e.target.value }))
                              }
                              className="text-xs font-mono font-bold bg-slate-50 border border-slate-200 rounded-lg p-1 text-slate-800 focus:bg-white"
                            >
                              {QUICK_TIME_SLOTS.map((slot) => (
                                <option key={slot} value={slot}>
                                  {slot}
                                </option>
                              ))}
                            </select>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}
                </div>
              )}

              {/* 수업 시간 (duration) 및 종료 시간 안내 */}
              <div className="grid grid-cols-2 gap-3 items-end">
                <div>
                  <label className="text-xs font-black text-slate-700 mb-1.5 block">수업 길이</label>
                  <select
                    value={durationMinutes}
                    onChange={(e) => setDurationMinutes(Number(e.target.value))}
                    className="w-full text-xs font-semibold border border-slate-200 rounded-xl px-3 py-2 bg-slate-50 focus:bg-white focus:outline-hidden focus:ring-2 focus:ring-indigo-500"
                  >
                    {DURATION_OPTIONS.map((opt) => (
                      <option key={opt.minutes} value={opt.minutes}>
                        {opt.label}
                      </option>
                    ))}
                  </select>
                </div>
                <div className="p-2 rounded-xl bg-slate-50 border border-slate-200 text-center">
                  <p className="text-[10px] text-slate-400 font-bold">시간표 슬롯</p>
                  <p className="text-xs font-mono font-black text-indigo-700 mt-0.5">
                    {startTime} ~ {endTime}
                  </p>
                </div>
              </div>

              {/* 반 이름 및 정원 */}
              <div className="grid grid-cols-3 gap-2">
                <div className="col-span-2">
                  <label className="text-xs font-black text-slate-700 mb-1.5 block">반 이름</label>
                  <input
                    type="text"
                    placeholder={autoGeneratedName}
                    value={customClassName}
                    onChange={(e) => setCustomClassName(e.target.value)}
                    className="w-full text-xs font-semibold border border-slate-200 rounded-xl px-3 py-2 focus:outline-hidden focus:ring-2 focus:ring-indigo-500"
                  />
                </div>
                <div>
                  <label className="text-xs font-black text-slate-700 mb-1.5 block">반 정원</label>
                  <input
                    type="number"
                    min={1}
                    max={30}
                    value={capacity}
                    onChange={(e) => setCapacity(Number(e.target.value))}
                    className="w-full text-xs font-semibold border border-slate-200 rounded-xl px-3 py-2 text-center focus:outline-hidden focus:ring-2 focus:ring-indigo-500"
                  />
                </div>
              </div>
            </div>
          ) : (
            /* MODE 2: 기존 반에 연결 */
            <div className="space-y-4">
              <div>
                <label className="text-xs font-black text-slate-700 flex items-center gap-1.5 mb-2">
                  <Building className="w-3.5 h-3.5 text-indigo-600" />
                  기존 개설된 반 선택
                </label>
                {existingClasses.length === 0 ? (
                  <p className="text-xs text-slate-400 p-4 border border-dashed rounded-xl text-center">
                    등록된 기존 반이 없습니다. '새 시간표 슬롯 생성'을 이용해주세요.
                  </p>
                ) : (
                  <div className="max-h-48 overflow-y-auto space-y-1.5 p-1">
                    {existingClasses.map((cls) => {
                      const isSelected = selectedExistingClassId === cls.id;
                      const enrolledCount = allStudents.filter((s) => s.classIds?.includes(cls.id)).length;
                      const cap = cls.capacity || 5;
                      const isFull = enrolledCount >= cap;

                      return (
                        <button
                          key={cls.id}
                          type="button"
                          onClick={() => setSelectedExistingClassId(cls.id)}
                          className={`w-full text-left p-3 rounded-2xl border transition-all cursor-pointer flex items-center justify-between gap-2 ${
                            isSelected
                              ? 'border-indigo-600 bg-indigo-50/70 ring-1 ring-indigo-500'
                              : 'border-slate-200 hover:border-indigo-200 hover:bg-slate-50'
                          }`}
                        >
                          <div className="min-w-0">
                            <p className="text-xs font-bold text-slate-900 truncate">{cls.name}</p>
                            <p className="text-[11px] text-slate-500 mt-0.5">
                              {cls.daysOfWeek?.join(',')} · {cls.startTime}~{cls.endTime} · {cls.room || '연습실'}
                            </p>
                          </div>
                          <div className="shrink-0 text-right">
                            <span
                              className={`text-[10px] font-bold px-1.5 py-0.5 rounded ${
                                isFull ? 'bg-rose-100 text-rose-700' : 'bg-emerald-100 text-emerald-700'
                              }`}
                            >
                              {enrolledCount}/{cap}명
                            </span>
                          </div>
                        </button>
                      );
                    })}
                  </div>
                )}
              </div>

              {/* 엣지 3번: 이미 배정된 학생 안내 */}
              {alreadyAssignedStudents.length > 0 && (
                <div className="p-2.5 rounded-xl bg-slate-100 text-slate-700 text-xs flex items-center justify-between">
                  <span>선택된 대상 중 <strong>{alreadyAssignedStudents.length}명</strong>은 이미 이 반에 등록됨</span>
                  <span className="text-[10px] font-bold text-slate-500">중복 방지</span>
                </div>
              )}

              {/* 엣지 2번: 정원 초과 경고 및 허용 체크박스 */}
              {isOverCapacity && (
                <div className="p-3 rounded-xl bg-rose-50 border border-rose-200 text-rose-900 text-xs space-y-2">
                  <div className="flex items-start gap-2 font-bold">
                    <AlertTriangle className="w-4 h-4 text-rose-600 shrink-0 mt-0.5" />
                    <div>
                      <p>정원 초과 경고 (최대 {maxCapacity}명)</p>
                      <p className="text-[11px] font-normal text-rose-700 mt-0.5">
                        현재 {existingEnrolledCount}명 + 신규 {newlyAddingCount}명 = 총 {expectedTotalCount}명이 배정됩니다.
                      </p>
                    </div>
                  </div>
                  <label className="flex items-center gap-2 cursor-pointer font-bold text-rose-950 pt-1">
                    <input
                      type="checkbox"
                      checked={allowOverCapacity}
                      onChange={(e) => setAllowOverCapacity(e.target.checked)}
                      className="rounded text-rose-600"
                    />
                    <span>정원 초과를 허용하고 계속 진행</span>
                  </label>
                </div>
              )}
            </div>
          )}
        </div>

        {/* 액션 버튼 */}
        <div className="p-5 sm:p-6 border-t border-slate-100 bg-slate-50/70 flex items-center justify-end gap-2.5">
          <button
            type="button"
            onClick={handleClose}
            className="px-4 py-2.5 rounded-xl border border-slate-200 text-slate-600 hover:bg-slate-100 text-xs font-bold transition-colors cursor-pointer"
          >
            취소
          </button>
          <button
            type="button"
            onClick={handleConfirmAssign}
            disabled={isOverCapacity && !allowOverCapacity}
            className={`min-h-[44px] px-5 py-2.5 rounded-xl text-white text-xs font-black shadow-md transition-all cursor-pointer flex items-center gap-1.5 ${
              isOverCapacity && !allowOverCapacity
                ? 'bg-slate-300 cursor-not-allowed text-slate-500 shadow-none'
                : 'bg-indigo-600 hover:bg-indigo-700 shadow-indigo-600/20'
            }`}
          >
            <CheckCircle2 className="w-4 h-4" />
            <span>
              {selectedStudents.length}명 일괄 배정 완료
            </span>
          </button>
        </div>
          </>
        )}
      </div>
    </div>
  );
};
